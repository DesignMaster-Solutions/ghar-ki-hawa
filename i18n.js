export function t(lang, key, vars = {}) {
  const s = STRINGS[lang]?.[key] ?? STRINGS.en[key];
  if (s === undefined) throw new Error(`missing string ${key}`);
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}
